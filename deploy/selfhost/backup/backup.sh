#!/bin/sh
# Backs up the cXML Dev Server SQLite database with sqlite3's online ".backup" command.
#
#   backup.sh [loop]   take a backup now, then every BACKUP_INTERVAL_HOURS hours (default mode, runs forever)
#   backup.sh once     take one backup and exit (non-zero if it failed)
#
# Each backup is written to a temporary name, checked with PRAGMA integrity_check and only then renamed to
# cxml-dev-<UTC timestamp>.db. Backups older than BACKUP_RETENTION_DAYS are deleted, but the newest one is always kept.
#
# Environment:
#   DB_PATH                 database file               (default /data/cxml-dev.db)
#   BACKUP_DIR              target folder               (default /backups)
#   BACKUP_INTERVAL_HOURS   hours between backups       (default 24)
#   BACKUP_RETENTION_DAYS   days to keep backups        (default 14)
#
# Restore: see the self-hosted runbook (stop the app, copy a backup over cxml-dev.db, delete cxml-dev.db-wal/-shm, start).

set -eu

APP_UID=1654
APP_GID=1654

# Started as root (the image default): fix ownership of the (bind-mounted) backup folder, then continue as the app user.
if [ "$(id -u)" = "0" ]; then
    mkdir -p "${BACKUP_DIR:-/backups}"
    chown "$APP_UID:$APP_GID" "${BACKUP_DIR:-/backups}"
    exec su-exec "$APP_UID:$APP_GID" "$0" "$@"
fi

DB_PATH="${DB_PATH:-/data/cxml-dev.db}"
BACKUP_DIR="${BACKUP_DIR:-/backups}"
BACKUP_INTERVAL_HOURS="${BACKUP_INTERVAL_HOURS:-24}"
BACKUP_RETENTION_DAYS="${BACKUP_RETENTION_DAYS:-14}"
MODE="${1:-loop}"

log() {
    printf '%s backup: %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$*"
}

is_positive_int() {
    case "$1" in
        '' | *[!0-9]*) return 1 ;;
        *) [ "$1" -ge 1 ] ;;
    esac
}

is_positive_int "$BACKUP_INTERVAL_HOURS" || { log "BACKUP_INTERVAL_HOURS must be a whole number >= 1 (got '$BACKUP_INTERVAL_HOURS')"; exit 2; }
is_positive_int "$BACKUP_RETENTION_DAYS" || { log "BACKUP_RETENTION_DAYS must be a whole number >= 1 (got '$BACKUP_RETENTION_DAYS')"; exit 2; }

prune() {
    # Keep the newest backup no matter how old it is, so a long outage of the app never leaves you without a backup.
    # (Only POSIX find options are used: "-delete" is missing from some busybox builds.)
    # shellcheck disable=SC2012 # file names are generated by this script (no spaces or newlines)
    newest="$(ls -1t "$BACKUP_DIR"/cxml-dev-*.db 2>/dev/null | head -n 1 || true)"
    find "$BACKUP_DIR" -maxdepth 1 -type f -name 'cxml-dev-*.db' ! -path "${newest:-/nonexistent}" \
        -mtime "+$BACKUP_RETENTION_DAYS" -print | while read -r old; do
        if rm -f "$old"; then log "pruned $old"; else log "could not delete $old"; fi
    done
    # Leftovers of an interrupted backup.
    find "$BACKUP_DIR" -maxdepth 1 -type f -name '.cxml-dev-*.partial' -mmin +60 -exec rm -f {} \;
    return 0
}

backup_once() {
    if [ ! -f "$DB_PATH" ]; then
        log "database $DB_PATH does not exist (yet)"
        return 1
    fi

    ts="$(date -u +%Y%m%dT%H%M%SZ)"
    partial="$BACKUP_DIR/.cxml-dev-$ts.partial"
    final="$BACKUP_DIR/cxml-dev-$ts.db"
    rm -f "$partial"

    # .timeout: wait for a writer instead of failing with "database is locked".
    if ! sqlite3 "$DB_PATH" ".timeout 30000" ".backup '$partial'"; then
        log "FAILED: sqlite3 .backup returned an error"
        rm -f "$partial"
        return 1
    fi

    result="$(sqlite3 "$partial" 'PRAGMA integrity_check;' 2>&1 || true)"
    if [ "$result" != "ok" ]; then
        log "FAILED: integrity_check of the copy reported: $result"
        rm -f "$partial"
        return 1
    fi

    mv "$partial" "$final"
    log "ok: $final ($(wc -c <"$final") bytes)"
    prune
}

case "$MODE" in
    once)
        backup_once
        ;;
    loop)
        # sleep runs in the background and the shell waits for it, so that SIGTERM (docker stop) is handled at once.
        sleeper=""
        trap 'log "stopping"; [ -z "$sleeper" ] || kill "$sleeper" 2>/dev/null; exit 0' TERM INT
        log "every $BACKUP_INTERVAL_HOURS h, keeping $BACKUP_RETENTION_DAYS days, $DB_PATH -> $BACKUP_DIR"
        while true; do
            backup_once || log "will retry in $BACKUP_INTERVAL_HOURS h"
            sleep "$((BACKUP_INTERVAL_HOURS * 3600))" &
            sleeper=$!
            wait "$sleeper" || true
        done
        ;;
    *)
        log "unknown mode '$MODE' (use: loop | once)"
        exit 2
        ;;
esac
